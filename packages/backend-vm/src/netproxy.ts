import { closeSync, openSync } from 'node:fs';
import { mkdir, open, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { AboxError, type NetworkEvent } from '@abox/core';
import { parseProxyLogLine, proxyRuntimeDir } from '@abox/proxy';
import { findInPath } from './qemu.js';
import { isProcessAlive, pathExists, writeFileAtomic } from './fsutil.js';
