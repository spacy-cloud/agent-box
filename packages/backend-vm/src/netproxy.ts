/**
 * Host side of the `allowlist` network mode: one abox egress proxy (packages/proxy) per
 * sandbox, listening on a unix socket inside the sandbox's private directory. QEMU's
 * `guestfwd` rule connects every guest connection to 10.0.2.100:3128 to that socket.
 *
 * The proxy program only knows TCP listening. A tiny launcher (written next to the config)
 * redirects its first `listen()` call to the unix socket, so the proxy is never reachable
 * from other local users or the network.
 */

const LAUNCHER = `// Generated by abox backend-vm. Runs the egress proxy on a unix socket instead of a TCP port.
import net from 'node:net';
import { pathToFileURL } from 'node:url';
const sock = process.env.ABOX_PROXY_SOCKET;
const script = process.env.ABOX_PROXY_SCRIPT;
if (!sock || !script) { console.error('launcher: missing environment'); process.exit(2); }
const orig = net.Server.prototype.listen;
let redirected = false;
net.Server.prototype.listen = function (...args) {
  if (!redirected) {
    redirected = true;
    const cb = args.find((a) => typeof a === 'function');
    return orig.call(this, sock, cb);
  }
  return orig.apply(this, args);
};
process.umask(0o077);
await import(pathToFileURL(script).href);
`;

/** Fallback relay when `socat` is not installed: bridges stdin/stdout to a unix socket. */
const RELAY = `// Generated by abox backend-vm.
import net from 'node:net';
const s = net.connect(process.argv[2]);
process.stdin.pipe(s);
s.pipe(process.stdout);
s.on('close', () => process.exit(0));
s.on('error', () => process.exit(1));
process.stdin.on('end', () => s.end());
`;

export interface ProxyHandle {
  pid: number;
  socketPath: string;
  logPath: string;
  /** Present when the proxy terminates TLS for injection hosts. */
  caCertPath?: string;
}

export function proxyPaths(
  dir: string,
  socketDir = dir,
): {
  config: string;
  socket: string;
  log: string;
  pid: string;
  state: string;
  launcher: string;
  relay: string;
  ca: string;
} {
  return {
    config: join(dir, 'config.json'),
    // unix socket paths are limited to ~100 characters and the guestfwd command allows only plain characters:
    // callers pass the short runtime directory
    socket: join(socketDir, 'proxy.sock'),
    log: join(dir, 'proxy.log'),
    pid: join(dir, 'proxy.pid'),
    state: join(dir, 'state'),
    launcher: join(dir, 'launcher.mjs'),
    relay: join(dir, 'relay.mjs'),
    ca: join(dir, 'state', 'ca.crt'),
  };
}

export function proxyScriptPath(): string {
  return join(proxyRuntimeDir, 'proxy.mjs');
}

/** The command QEMU's `guestfwd` runs per guest connection: `socat` if present, else a Node relay. */
export async function relayArgv(dir: string, socketDir = dir): Promise<string[]> {
  const p = proxyPaths(dir, socketDir);
  const socat = findInPath('socat');
  if (socat) return [socat, 'STDIO', `UNIX-CONNECT:${p.socket}`];
  await writeFile(p.relay, RELAY, { mode: 0o600 });
  return [process.execPath, p.relay, p.socket];
}

async function readPid(file: string): Promise<number | undefined> {
  const n = Number((await readFile(file, 'utf8').catch(() => '')).trim());
  return Number.isInteger(n) && n > 0 ? n : undefined;
}

async function cmdlineOf(pid: number): Promise<string> {
  return (await readFile(`/proc/${pid}/cmdline`, 'latin1').catch(() => '')).replaceAll('\0', ' ');
}

export async function isProxyAlive(dir: string): Promise<boolean> {
  const pid = await readPid(proxyPaths(dir).pid);
  if (pid === undefined || !isProcessAlive(pid)) return false;
  return (await cmdlineOf(pid)).includes('launcher.mjs');
}

export function toProxyConfig(net: NetFile, stateDir: string): Record<string, unknown> {
  return {
    listen: { host: '127.0.0.1', port: 0 },
    allow: net.allow,
    blockPrivate: net.blockPrivate,
    privateExceptions: net.privateExceptions,
    injections: net.injections,
    stateDir,
  };
}

/** Starts the proxy (replacing a stale one) and waits until it listens. */
export async function startProxy(
  dir: string,
  net: NetFile,
  socketDir = dir,
  timeoutMs = 20_000,
): Promise<ProxyHandle> {
  await stopProxy(dir, socketDir);
  const p = proxyPaths(dir, socketDir);
  await mkdir(dir, { recursive: true, mode: 0o700 });
  await mkdir(socketDir, { recursive: true, mode: 0o700 });
  await rm(p.state, { recursive: true, force: true });
  await rm(p.socket, { force: true });
  // Keep the log of earlier runs short.
  const old = await stat(p.log).catch(() => undefined);
  const logFlags = old && old.size > 5 * 1024 * 1024 ? 'w' : 'a';
  await writeFileAtomic(p.config, JSON.stringify(toProxyConfig(net, p.state)), 0o600);
  await writeFile(p.launcher, LAUNCHER, { mode: 0o600 });
  const logFd = openSync(p.log, logFlags, 0o600);
  const startedAt = Date.now();
  const child = spawn(process.execPath, [p.launcher, p.config], {
    detached: true,
    stdio: ['ignore', logFd, logFd],
    cwd: dir,
    env: {
      PATH: process.env['PATH'] ?? '/usr/bin:/bin',
      ABOX_PROXY_SOCKET: p.socket,
      ABOX_PROXY_SCRIPT: proxyScriptPath(),
    },
  });
  closeSync(logFd);
  let early: number | null | undefined;
  child.on('exit', (code) => {
    early = code;
  });
  child.unref();
  const pid = child.pid;
  if (pid === undefined) throw new AboxError('backend_error', 'could not start the egress proxy');
  await writeFile(p.pid, String(pid), { mode: 0o600 });
  for (;;) {
    if (early !== undefined) {
      const tail = (await readFile(p.log, 'utf8').catch(() => '')).split('\n').slice(-5).join('\n');
      throw new AboxError(
        'backend_error',
        `the egress proxy exited during startup (code ${String(early)}): ${tail.slice(-400)}`,
      );
    }
    if ((await pathExists(p.socket)) && (await readyLogged(p.log, startedAt))) break;
    if (Date.now() - startedAt > timeoutMs) {
      await stopProxy(dir, socketDir);
      throw new AboxError('timeout', 'the egress proxy did not become ready');
    }
    await sleep(50);
  }
  return {
    pid,
    socketPath: p.socket,
    logPath: p.log,
    ...(net.injections.length > 0 ? { caCertPath: p.ca } : {}),
  };
}

async function readyLogged(log: string, since: number): Promise<boolean> {
  const text = await readFile(log, 'utf8').catch(() => '');
  for (const line of text.split('\n').reverse()) {
    const ev = parseProxyLogLine(line);
    if (ev && 'event' in ev && ev.event === 'ready') {
      try {
        const obj = JSON.parse(line) as { ts?: number };
        return typeof obj.ts !== 'number' || obj.ts >= since - 1000;
      } catch {
        return true;
      }
    }
  }
  return false;
}

export async function stopProxy(dir: string, socketDir = dir): Promise<void> {
  const p = proxyPaths(dir, socketDir);
  const pid = await readPid(p.pid);
  if (pid !== undefined && isProcessAlive(pid) && (await cmdlineOf(pid)).includes('launcher.mjs')) {
    try {
      process.kill(pid, 'SIGTERM');
    } catch {
      /* gone */
    }
    for (let i = 0; i < 40 && isProcessAlive(pid); i++) await sleep(50);
    if (isProcessAlive(pid)) {
      try {
        process.kill(pid, 'SIGKILL');
      } catch {
        /* gone */
      }
    }
  }
  await rm(p.pid, { force: true });
  await rm(p.socket, { force: true });
}

/** Egress decisions in the proxy log since `sinceTs` (ms). */
export async function readNetworkEvents(logPath: string, sinceTs = 0): Promise<NetworkEvent[]> {
  const fh = await open(logPath, 'r').catch(() => undefined);
  if (!fh) return [];
  try {
    const st = await fh.stat();
    // The proxy log is capped on restart; read at most the last 8 MiB.
    const len = Math.min(st.size, 8 * 1024 * 1024);
    const buf = Buffer.alloc(len);
    await fh.read(buf, 0, len, st.size - len);
    const out: NetworkEvent[] = [];
    for (const line of buf.toString('utf8').split('\n')) {
      const ev = parseProxyLogLine(line);
      if (ev && 'decision' in ev && ev.ts >= sinceTs) out.push(ev);
    }
    return out;
  } finally {
    await fh.close();
  }
}
