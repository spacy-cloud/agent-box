import type { Command } from 'commander';
import { Argument } from 'commander';
import type { Cli } from '../cli.js';

interface Node {
  path: string;
  description: string;
  subs: Array<{ name: string; description: string }>;
  flags: string[];
  choices: Record<string, string[]>;
  fileFlags: string[];
  /** First positional is a sandbox id. */
  ids: boolean;
  files: boolean;
  /** Fixed values of the first positional argument (e.g. the shell of `completion`). */
  posChoices: string[];
}

const HIDDEN = new Set(['__ids']);
const FILE_FLAGS = new Set(['--out', '--workspace', '--path']);
const FILE_COMMANDS = new Set(['cp', 'template validate', 'skill validate', 'policy validate']);

export function collectNodes(program: Command): Node[] {
  const globalFlags = program.options.flatMap((o) =>
    [o.long, o.short].filter((x): x is string => !!x),
  );
  const nodes: Node[] = [];
  const walk = (cmd: Command, path: string[]): void => {
    const own = cmd.options.flatMap((o) => [o.long, o.short].filter((x): x is string => !!x));
    const key = path.join(' ');
    const choices: Record<string, string[]> = {};
    const fileFlags: string[] = [];
    for (const o of [...program.options, ...cmd.options]) {
      if (o.argChoices && o.argChoices.length > 0) {
        for (const f of [o.long, o.short]) if (f) choices[f] = [...o.argChoices];
      }
      if (o.long && FILE_FLAGS.has(o.long)) fileFlags.push(o.long);
    }
    const subs = cmd.commands
      .filter((c) => !HIDDEN.has(c.name()))
      .map((c) => ({ name: c.name(), description: c.description() }));
    if (path.length === 0) subs.push({ name: 'help', description: 'Show help for a command' });
    nodes.push({
      path: key,
      description: cmd.description(),
      subs,
      flags: [...new Set([...own, ...(path.length === 0 ? [] : []), ...globalFlags, '--help'])],
      choices,
      fileFlags,
      ids: cmd.registeredArguments[0]?.name() === 'id' && cmd.commands.length === 0,
      files: FILE_COMMANDS.has(key),
      posChoices:
        cmd.commands.length === 0 ? [...(cmd.registeredArguments[0]?.argChoices ?? [])] : [],
    });
    for (const c of cmd.commands) if (!HIDDEN.has(c.name())) walk(c, [...path, c.name()]);
  };
  walk(program, []);
  return nodes;
}

const q = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`;
const firstLine = (s: string): string => s.split('\n')[0]!.replace(/\s+/g, ' ').trim();

function caseTable(nodes: Node[], fn: (n: Node) => string | undefined, indent = '    '): string {
  const lines: string[] = [];
  for (const n of nodes) {
    const v = fn(n);
    if (v === undefined || v === '') continue;
    lines.push(`${indent}${n.path === '' ? "''" : q(n.path)}) ${v} ;;`);
  }
  return lines.join('\n');
}

function shellFunctions(nodes: Node[]): string {
  const choiceCases: string[] = [];
  for (const n of nodes) {
    for (const [flag, vals] of Object.entries(n.choices)) {
      choiceCases.push(`    ${q(`${n.path}|${flag}`)}) echo ${q(vals.join(' '))} ;;`);
    }
  }
  const fileOpt: string[] = [];
  for (const n of nodes) {
    for (const f of n.fileFlags) fileOpt.push(`    ${q(`${n.path}|${f}`)}) echo files ;;`);
  }
  return `_abox_subs() {
  case "$1" in
${caseTable(nodes, (n) => (n.subs.length ? `echo ${q(n.subs.map((s) => s.name).join(' '))}` : undefined))}
  esac
}
_abox_flags() {
  case "$1" in
${caseTable(nodes, (n) => `echo ${q(n.flags.join(' '))}`)}
  esac
}
_abox_choices() {
  case "$1|$2" in
${choiceCases.join('\n')}
  esac
}
_abox_optkind() {
  case "$1|$2" in
${fileOpt.join('\n')}
  esac
}
_abox_kind() {
  case "$1" in
${caseTable(nodes, (n) => (n.ids ? 'echo ids' : n.files ? 'echo files' : undefined))}
  esac
}
_abox_posargs() {
  case "$1" in
${caseTable(nodes, (n) => (n.posChoices.length ? `echo ${q(n.posChoices.join(' '))}` : undefined))}
  esac
}
`;
}

export function bashCompletion(program: Command): string {
  const nodes = collectNodes(program);
  return `# bash completion for abox (generated by "abox completion bash")
# Install: abox completion bash > ~/.local/share/bash-completion/completions/abox
${shellFunctions(nodes)}
_abox() {
  local cur="\${COMP_WORDS[COMP_CWORD]}" prev="" path="" i w
  if (( COMP_CWORD > 0 )); then prev="\${COMP_WORDS[COMP_CWORD-1]}"; fi
  COMPREPLY=()
  for (( i = 1; i < COMP_CWORD; i++ )); do
    w="\${COMP_WORDS[i]}"
    if [[ " $(_abox_subs "$path") " == *" $w "* ]]; then path="\${path:+$path }$w"; fi
  done
  local choices
  choices="$(_abox_choices "$path" "$prev")"
  if [[ -n "$choices" ]]; then
    COMPREPLY=( $(compgen -W "$choices" -- "$cur") )
    return 0
  fi
  if [[ "$(_abox_optkind "$path" "$prev")" == files ]]; then
    COMPREPLY=( $(compgen -f -- "$cur") )
    return 0
  fi
  if [[ "$cur" == -* ]]; then
    COMPREPLY=( $(compgen -W "$(_abox_flags "$path")" -- "$cur") )
    return 0
  fi
  local subs
  subs="$(_abox_subs "$path")"
  if [[ -n "$subs" ]]; then
    COMPREPLY=( $(compgen -W "$subs" -- "$cur") )
    return 0
  fi
  local pos
  pos="$(_abox_posargs "$path")"
  if [[ -n "$pos" ]]; then
    COMPREPLY=( $(compgen -W "$pos" -- "$cur") )
    return 0
  fi
  case "$(_abox_kind "$path")" in
    ids) COMPREPLY=( $(compgen -W "$(abox __ids 2>/dev/null)" -- "$cur") ) ;;
    files) COMPREPLY=( $(compgen -f -- "$cur") ) ;;
  esac
  return 0
}
complete -F _abox abox
`;
}

export function zshCompletion(program: Command): string {
  const nodes = collectNodes(program);
  const descCases = caseTable(nodes, (n) =>
    n.subs.length
      ? `print -rl -- ${n.subs.map((s) => q(`${s.name}:${firstLine(s.description).replace(/:/g, '\\:')}`)).join(' ')}`
      : undefined,
  );
  return `#compdef abox
# zsh completion for abox (generated by "abox completion zsh")
# Install: abox completion zsh > "\${fpath[1]}/_abox"   (or: source <(abox completion zsh))
${shellFunctions(nodes)}
_abox_subs_desc() {
  case "$1" in
${descCases}
  esac
}
_abox() {
  local cur="\${words[CURRENT]}" prev="" path="" i w
  (( CURRENT > 1 )) && prev="\${words[CURRENT-1]}"
  for (( i = 2; i < CURRENT; i++ )); do
    w="\${words[i]}"
    if [[ " $(_abox_subs "$path") " == *" $w "* ]]; then path="\${path:+$path }$w"; fi
  done
  local choices
  choices="$(_abox_choices "$path" "$prev")"
  if [[ -n "$choices" ]]; then
    compadd -- \${=choices}
    return 0
  fi
  if [[ "$(_abox_optkind "$path" "$prev")" == files ]]; then
    _files
    return 0
  fi
  if [[ "$cur" == -* ]]; then
    compadd -- \${=$(_abox_flags "$path")}
    return 0
  fi
  local -a items
  items=( \${(f)"$(_abox_subs_desc "$path")"} )
  if (( \${#items} > 0 )); then
    _describe -t commands 'abox command' items
    return 0
  fi
  local pos
  pos="$(_abox_posargs "$path")"
  if [[ -n "$pos" ]]; then
    compadd -- \${=pos}
    return 0
  fi
  case "$(_abox_kind "$path")" in
    ids) compadd -- \${(f)"$(abox __ids 2>/dev/null)"} ;;
    files) _files ;;
  esac
  return 0
}
if [ "\${funcstack[1]}" = "_abox" ]; then
  _abox "$@"
else
  compdef _abox abox
fi
`;
}

export function fishCompletion(program: Command): string {
  const nodes = collectNodes(program);
  const fq = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const fcase = (fn: (n: Node) => string | undefined): string => {
    const lines: string[] = [];
    for (const n of nodes) {
      const v = fn(n);
      if (v === undefined || v === '') continue;
      lines.push(`        case ${fq(n.path)}\n            ${v}`);
    }
    return lines.join('\n');
  };
  const choiceCases: string[] = [];
  const fileOpt: string[] = [];
  for (const n of nodes) {
    for (const [flag, vals] of Object.entries(n.choices))
      choiceCases.push(
        `        case ${fq(`${n.path}|${flag}`)}\n            echo ${fq(vals.join(' '))}`,
      );
    for (const f of n.fileFlags)
      fileOpt.push(`        case ${fq(`${n.path}|${f}`)}\n            echo files`);
  }
  return `# fish completion for abox (generated by "abox completion fish")
# Install: abox completion fish > ~/.config/fish/completions/abox.fish
function __abox_subs_for
    switch "$argv[1]"
${fcase((n) =>
  n.subs.length
    ? `printf '%s\\t%s\\n' ${n.subs.map((s) => `${fq(s.name)} ${fq(firstLine(s.description))}`).join(' ')}`
    : undefined,
)}
    end
end
function __abox_flags_for
    switch "$argv[1]"
${fcase((n) => `printf '%s\\n' ${n.flags.map(fq).join(' ')}`)}
    end
end
function __abox_choices_for
    switch "$argv[1]|$argv[2]"
${choiceCases.join('\n')}
    end
end
function __abox_optkind_for
    switch "$argv[1]|$argv[2]"
${fileOpt.join('\n')}
    end
end
function __abox_kind_for
    switch "$argv[1]"
${fcase((n) => (n.ids ? 'echo ids' : n.files ? 'echo files' : undefined))}
    end
end
function __abox_posargs_for
    switch "$argv[1]"
${fcase((n) => (n.posChoices.length ? `printf '%s\\n' ${n.posChoices.map(fq).join(' ')}` : undefined))}
    end
end
function __abox_current_path
    set -l path ''
    set -l tokens (commandline -opc)
    set -e tokens[1]
    for w in $tokens
        set -l subs (__abox_subs_for $path | string split -f1 \\t)
        if contains -- $w $subs
            set path (string trim -- "$path $w")
        end
    end
    echo $path
end
function __abox_prev
    set -l tokens (commandline -opc)
    echo $tokens[-1]
end
function __abox_complete
    set -l path (__abox_current_path)
    set -l cur (commandline -ct)
    set -l prev (__abox_prev)
    set -l choices (__abox_choices_for "$path" "$prev")
    if test -n "$choices"
        printf '%s\\n' (string split ' ' -- $choices)
        return
    end
    if test (__abox_optkind_for "$path" "$prev") = files
        return
    end
    if string match -q -- '-*' "$cur"
        __abox_flags_for "$path"
        return
    end
    set -l subs (__abox_subs_for "$path")
    if test (count $subs) -gt 0
        printf '%s\\n' $subs
        return
    end
    set -l pos (__abox_posargs_for "$path")
    if test (count $pos) -gt 0
        printf '%s\\n' $pos
        return
    end
    if test (__abox_kind_for "$path") = ids
        abox __ids 2>/dev/null
    end
end
function __abox_wants_files
    set -l path (__abox_current_path)
    set -l prev (__abox_prev)
    test (__abox_optkind_for "$path" "$prev") = files; and return 0
    string match -q -- '-*' (commandline -ct); and return 1
    test (count (__abox_subs_for "$path")) -eq 0; and test (__abox_kind_for "$path") = files
end
complete -c abox -f -a '(__abox_complete)'
complete -c abox -n '__abox_wants_files' -F
`;
}

export function registerCompletion(program: Command, cli: Cli): void {
  program
    .command('completion')
    .description('Print a shell completion script (bash, zsh or fish)')
    .addArgument(new Argument('<shell>', 'target shell').choices(['bash', 'zsh', 'fish']))
    .action((shell: 'bash' | 'zsh' | 'fish') => {
      const script =
        shell === 'bash'
          ? bashCompletion(program)
          : shell === 'zsh'
            ? zshCompletion(program)
            : fishCompletion(program);
      if (cli.json) cli.success({ shell, script });
      else cli.out(script);
    });

  // Hidden helper for the completion scripts: sandbox ids, one per line, never an error.
  program
    .command('__ids', { hidden: true })
    .description('Print sandbox ids (for shell completion)')
    .action(async () => {
      try {
        const rt = await cli.rt({ reconcileOnOpen: false });
        const { sandboxes } = await rt.abox.listSandboxes(cli.caller());
        for (const s of sandboxes) cli.out(`${s.id}\n`);
      } catch {
        /* completion must stay silent */
      }
    });
}
